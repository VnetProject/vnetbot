error_reporting(E_ALL);
ini_set('display_errors', '1');

$configPath = __DIR__ . '/config.php';
$alreadyInstalled = file_exists($configPath);
$forceReinstall = isset($_POST['force_reinstall']);
$errors = [];
$success = false;
$webhookInfo = null;

function guess_base_url(): string
{
    $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
    $host = $_SERVER['HTTP_HOST'] ?? 'yourdomain.com';
    $dir = rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'])), '/');
    return "$scheme://$host$dir";
}

if ($_SERVER['REQUEST_METHOD'] === 'POST' && (!$alreadyInstalled || $forceReinstall)) {
    $botToken = trim($_POST['bot_token'] ?? '');
    $adminIds = trim($_POST['admin_ids'] ?? '');
    $dbHost = trim($_POST['db_host'] ?? 'localhost');
    $dbName = trim($_POST['db_name'] ?? '');
    $dbUser = trim($_POST['db_user'] ?? '');
    $dbPass = $_POST['db_pass'] ?? '';

    if ($botToken === '' || !str_contains($botToken, ':')) {
        $errors[] = 'توکن ربات معتبر نیست.';
    }
    if ($adminIds === '' || !preg_match('/^\d+(,\s*\d+)*$/', $adminIds)) {
        $errors[] = 'آیدی عددی ادمین باید فقط عدد باشه (چند تا رو با کاما جدا کن).';
    }
    if ($dbName === '' || $dbUser === '') {
        $errors[] = 'نام دیتابیس و یوزرنیم دیتابیس رو وارد کن.';
    }

    $pdo = null;
    if (!$errors) {
        try {
            $pdo = new PDO("mysql:host=$dbHost;dbname=$dbName;charset=utf8mb4", $dbUser, $dbPass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        } catch (Exception $e) {
            $errors[] = 'اتصال به دیتابیس ناموفق بود: ' . $e->getMessage();
        }
    }

    if (!$errors && $pdo) {
        require __DIR__ . '/includes/schema.php';
        ensure_schema($pdo);

        $webhookSecret = bin2hex(random_bytes(16));
        $adminIdsArray = array_map('intval', array_map('trim', explode(',', $adminIds)));
        $adminIdsPhp = '[' . implode(', ', $adminIdsArray) . ']';

        $configContent = "<?php\n"
            . "// Generated by installer.php on " . date('Y-m-d H:i:s') . "\n"
            . "define('BOT_TOKEN', " . var_export($botToken, true) . ");\n"
            . "define('ADMIN_IDS', $adminIdsPhp);\n"
            . "define('WEBHOOK_SECRET', " . var_export($webhookSecret, true) . ");\n"
            . "define('DB_HOST', " . var_export($dbHost, true) . ");\n"
            . "define('DB_NAME', " . var_export($dbName, true) . ");\n"
            . "define('DB_USER', " . var_export($dbUser, true) . ");\n"
            . "define('DB_PASS', " . var_export($dbPass, true) . ");\n"
            . "define('TRONSCAN_API_KEY', '');\n"
            . "define('CRYPTO_ORDER_TTL_MINUTES', 30);\n";

        if (file_put_contents($configPath, $configContent) === false) {
            $errors[] = 'نوشتن فایل config.php ناموفق بود — مطمئن شو پوشه قابل نوشتن (writable) هست.';
        } else {
            require $configPath;
            require __DIR__ . '/includes/db.php';
            require __DIR__ . '/includes/content.php';
            seed_defaults();
            set_text('schema.version', SCHEMA_VERSION);

            $baseUrl = trim($_POST['base_url'] ?? '') ?: guess_base_url();
            set_text('site.base_url', rtrim($baseUrl, '/'));
            $webhookUrl = rtrim($baseUrl, '/') . '/webhook.php';

            require __DIR__ . '/includes/telegram.php';
            $result = tg_api('setWebhook', ['url' => $webhookUrl, 'secret_token' => $webhookSecret, 'allowed_updates' => ['message', 'callback_query']]);
            $webhookInfo = ['url' => $webhookUrl, 'result' => $result];
            $success = (bool) ($result['ok'] ?? false);
            if (!$success) {
                $errors[] = 'تنظیم Webhook ناموفق بود: ' . ($result['description'] ?? 'خطای نامشخص');
            }
        }
    }
}
