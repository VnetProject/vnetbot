    </ol>
  </div>
<?php else: ?>

  <?php if ($alreadyInstalled && !$forceReinstall): ?>
    <div class="err">
      این ربات قبلاً نصب شده (فایل <code>config.php</code> وجود داره). اگه می‌خوای دوباره نصب کنی (مثلاً اطلاعات دیتابیس عوض شده)،
