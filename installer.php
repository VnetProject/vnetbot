    </form>
  <?php else: ?>

    <?php foreach ($errors as $e): ?><div class="err">❌ <?= htmlspecialchars($e) ?></div><?php endforeach; ?>

    <form method="post">
      <?php if ($forceReinstall): ?><input type="hidden" name="force_reinstall" value="1"><?php endif; ?>

      <label>توکن ربات (از @BotFather)</label>
