      <input type="text" name="db_name" value="<?= htmlspecialchars($_POST['db_name'] ?? '') ?>" required>
      <div class="hint">اگه قبلاً ربات رو نصب کرده بودی، همون دیتابیس قبلی رو وارد کن؛ اطلاعات قبلی (کاربرها، سرویس‌ها، متن‌ها) پاک نمی‌شه و فقط ستون‌های جدید اضافه می‌شن.</div>

